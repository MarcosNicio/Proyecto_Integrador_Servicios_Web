-- =============================================================================
-- BASE DE DATOS: veterinaria_db (PostgreSQL)
-- Adaptado del script DDL de la especificación técnica (24 tablas)
-- Ejecutar conectado a la base veterinaria_db:
--   psql -U postgres -h localhost -p 5433 -d veterinaria_db -f veterinaria_db.sql
