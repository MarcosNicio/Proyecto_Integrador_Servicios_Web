BEGIN;

-- 1. USUARIOS Y SEGURIDAD
CREATE TABLE USUARIOS (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN', 'VETERINARIO', 'CAJERO', 'CLIENTE')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. CLIENTES Y PACIENTES
CREATE TABLE CLIENTES (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT UNIQUE NULL,
    nombre VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    direccion VARCHAR(255) NULL,
    responsiva_url VARCHAR(255) NULL,
    CONSTRAINT fk_cliente_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIOS(id_usuario) ON DELETE SET NULL
);

CREATE TABLE RESPONSABLES_EXTRA (
    id_responsable INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL,
    nombre_completo VARCHAR(150) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    parentesco VARCHAR(50) NULL,
    CONSTRAINT fk_responsable_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTES(id_cliente) ON DELETE CASCADE
);

CREATE TABLE MASCOTAS (
    id_mascota INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    especie VARCHAR(50) NOT NULL,
    raza VARCHAR(80) NULL,
    fecha_nacimiento DATE NULL,
    peso_actual_kg DECIMAL(5,2) NULL,
    sexo VARCHAR(10) NOT NULL CHECK (sexo IN ('MACHO', 'HEMBRA')),
    esterilizado BOOLEAN NOT NULL DEFAULT FALSE,
    foto_url VARCHAR(255) NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_mascota_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTES(id_cliente) ON DELETE CASCADE
);

CREATE TABLE ANTECEDENTES_CLINICOS (
    id_antecedente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota INT NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('ALERGIA', 'ENFERMEDAD_CRONICA', 'CIRUGIA_PREVIA')),
    descripcion TEXT NOT NULL,
    fecha_registro DATE NOT NULL,
    CONSTRAINT fk_antecedente_mascota FOREIGN KEY (id_mascota) REFERENCES MASCOTAS(id_mascota) ON DELETE CASCADE
);

-- 3. PERSONAL Y DISPONIBILIDAD
CREATE TABLE PERSONAL (
    id_personal INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT UNIQUE NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    cedula_profesional VARCHAR(50) NULL,
    especialidad_especies VARCHAR(150) NULL,
    CONSTRAINT fk_personal_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIOS(id_usuario) ON DELETE CASCADE
);

CREATE TABLE HORARIOS_PERSONAL (
    id_horario_personal INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL,
    dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT fk_horario_personal FOREIGN KEY (id_personal) REFERENCES PERSONAL(id_personal) ON DELETE CASCADE
);

CREATE TABLE BLOQUEOS_DISPONIBILIDAD (
    id_bloqueo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    motivo VARCHAR(30) NOT NULL CHECK (motivo IN ('PERSONAL', 'CIRUGIA', 'DIA_LIBRE')),
    notas VARCHAR(255) NULL,
    CONSTRAINT fk_bloqueo_personal FOREIGN KEY (id_personal) REFERENCES PERSONAL(id_personal) ON DELETE CASCADE
);

-- 4. INFRAESTRUCTURA Y SERVICIOS
CREATE TABLE HORARIOS_CLINICA (
    id_horario_clinica INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana SMALLINT NOT NULL UNIQUE CHECK (dia_semana BETWEEN 0 AND 6),
    hora_apertura TIME NOT NULL,
    hora_cierre TIME NOT NULL,
    laborable BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE TIPOS_CONSULTORIO (
    id_tipo_consultorio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255) NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE CONSULTORIOS (
    id_consultorio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_consultorio INT NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_consultorio_tipo FOREIGN KEY (id_tipo_consultorio) REFERENCES TIPOS_CONSULTORIO(id_tipo_consultorio)
);

CREATE TABLE CATEGORIAS_SERVICIO (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255) NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE SERVICIOS (
    id_servicio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INT NOT NULL,
    id_tipo_consultorio INT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT NULL,
    duracion_minutos INT NOT NULL,
    precio_base DECIMAL(10,2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_servicio_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIAS_SERVICIO(id_categoria),
    CONSTRAINT fk_servicio_tipo_consultorio FOREIGN KEY (id_tipo_consultorio) REFERENCES TIPOS_CONSULTORIO(id_tipo_consultorio)
);

CREATE TABLE TARIFAS_SERVICIO (
    id_tarifa INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio INT NOT NULL,
    especie VARCHAR(50) NOT NULL,
    peso_min_kg DECIMAL(5,2) NOT NULL,
    peso_max_kg DECIMAL(5,2) NOT NULL,
    precio_calculado DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_tarifa_servicio FOREIGN KEY (id_servicio) REFERENCES SERVICIOS(id_servicio) ON DELETE CASCADE
);

-- 5. INVENTARIO
CREATE TABLE INVENTARIO_PRODUCTOS (
    id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('MEDICAMENTO', 'INSUMO_CLINICO', 'TIENDA')),
    unidad_medida VARCHAR(30) NOT NULL,
    precio_unitario DECIMAL(10,2) NOT NULL,
    stock_actual INT NOT NULL DEFAULT 0,
    stock_minimo INT NOT NULL DEFAULT 5,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE MOVIMIENTOS_INVENTARIO (
    id_movimiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INT NOT NULL,
    id_usuario INT NOT NULL,
    tipo_movimiento VARCHAR(30) NOT NULL CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA_CONSULTA', 'SALIDA_VENTA', 'AJUSTE')),
    cantidad INT NOT NULL,
    referencia VARCHAR(120) NULL,
    fecha_movimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_movimiento_producto FOREIGN KEY (id_producto) REFERENCES INVENTARIO_PRODUCTOS(id_producto),
    CONSTRAINT fk_movimiento_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIOS(id_usuario)
);

-- 6. AGENDA Y CITAS
CREATE TABLE CITAS (
    id_cita INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota INT NOT NULL,
    id_servicio INT NOT NULL,
    id_veterinario INT NOT NULL,
    id_consultorio INT NULL,
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    costo_estimado DECIMAL(10,2) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'EN_SALA_ESPERA', 'EN_ATENCION', 'COMPLETADA', 'CANCELADA')),
    notas TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cita_mascota FOREIGN KEY (id_mascota) REFERENCES MASCOTAS(id_mascota),
    CONSTRAINT fk_cita_servicio FOREIGN KEY (id_servicio) REFERENCES SERVICIOS(id_servicio),
    CONSTRAINT fk_cita_veterinario FOREIGN KEY (id_veterinario) REFERENCES PERSONAL(id_personal),
    CONSTRAINT fk_cita_consultorio FOREIGN KEY (id_consultorio) REFERENCES CONSULTORIOS(id_consultorio)
);

-- 7. EXPEDIENTE CLÍNICO
CREATE TABLE CONSULTAS_SOAP (
    id_consulta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita INT UNIQUE NOT NULL,
    id_mascota INT NOT NULL,
    id_veterinario INT NOT NULL,
    fecha_consulta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_consulta TEXT NOT NULL,
    peso_kg DECIMAL(5,2) NULL,
    temperatura_c DECIMAL(4,1) NULL,
    frecuencia_cardiaca INT NULL,
    frecuencia_respiratoria INT NULL,
    diagnostico TEXT NOT NULL,
    observaciones_plan TEXT NULL,
    CONSTRAINT fk_soap_cita FOREIGN KEY (id_cita) REFERENCES CITAS(id_cita),
    CONSTRAINT fk_soap_mascota FOREIGN KEY (id_mascota) REFERENCES MASCOTAS(id_mascota),
    CONSTRAINT fk_soap_veterinario FOREIGN KEY (id_veterinario) REFERENCES PERSONAL(id_personal)
);

CREATE TABLE RECETAS_MEDICAS (
    id_receta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta INT NOT NULL,
    medicamentos_dosis TEXT NOT NULL,
    indicaciones TEXT NULL,
    archivo_pdf_url VARCHAR(255) NULL,
    fecha_emision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_receta_consulta FOREIGN KEY (id_consulta) REFERENCES CONSULTAS_SOAP(id_consulta) ON DELETE CASCADE
);

CREATE TABLE CARNET_VACUNACION (
    id_carnet INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota INT NOT NULL,
    id_consulta INT NULL,
    id_producto INT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('VACUNA', 'DESPARASITACION')),
    nombre_biologico VARCHAR(120) NOT NULL,
    lote VARCHAR(50) NULL,
    fecha_aplicacion DATE NOT NULL,
    fecha_proxima_dosis DATE NULL,
    CONSTRAINT fk_carnet_mascota FOREIGN KEY (id_mascota) REFERENCES MASCOTAS(id_mascota) ON DELETE CASCADE,
    CONSTRAINT fk_carnet_consulta FOREIGN KEY (id_consulta) REFERENCES CONSULTAS_SOAP(id_consulta) ON DELETE SET NULL,
    CONSTRAINT fk_carnet_producto FOREIGN KEY (id_producto) REFERENCES INVENTARIO_PRODUCTOS(id_producto) ON DELETE SET NULL
);

-- 8. COBROS Y CAJA
CREATE TABLE ORDENES_COBRO (
    id_orden INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita INT NULL,
    id_cliente INT NOT NULL,
    id_veterinario INT NULL,
    id_cajero INT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_COBRO' CHECK (estado IN ('PENDIENTE_COBRO', 'PAGADA', 'CANCELADA')),
    subtotal DECIMAL(10,2) NOT NULL,
    impuestos DECIMAL(10,2) NOT NULL,
    total DECIMAL(10,2) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_orden_cita FOREIGN KEY (id_cita) REFERENCES CITAS(id_cita) ON DELETE SET NULL,
    CONSTRAINT fk_orden_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTES(id_cliente),
    CONSTRAINT fk_orden_veterinario FOREIGN KEY (id_veterinario) REFERENCES PERSONAL(id_personal),
    CONSTRAINT fk_orden_cajero FOREIGN KEY (id_cajero) REFERENCES PERSONAL(id_personal)
);

CREATE TABLE ORDEN_DETALLES (
    id_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden INT NOT NULL,
    tipo_item VARCHAR(30) NOT NULL CHECK (tipo_item IN ('SERVICIO', 'INSUMO_CLINICO', 'PRODUCTO_TIENDA')),
    id_servicio INT NULL,
    id_producto INT NULL,
    descripcion_snapshot VARCHAR(150) NOT NULL,
    cantidad INT NOT NULL,
    precio_unitario_snapshot DECIMAL(10,2) NOT NULL,
    subtotal DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_detalle_orden FOREIGN KEY (id_orden) REFERENCES ORDENES_COBRO(id_orden) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_servicio FOREIGN KEY (id_servicio) REFERENCES SERVICIOS(id_servicio),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES INVENTARIO_PRODUCTOS(id_producto)
);

CREATE TABLE PAGOS (
    id_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden INT NOT NULL,
    metodo_pago VARCHAR(30) NOT NULL CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
    monto DECIMAL(10,2) NOT NULL,
    referencia_pago VARCHAR(100) NULL,
    folio_recibo VARCHAR(50) NOT NULL UNIQUE,
    recibo_pdf_url VARCHAR(255) NULL,
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pago_orden FOREIGN KEY (id_orden) REFERENCES ORDENES_COBRO(id_orden) ON DELETE CASCADE
);

-- 9. NOTIFICACIONES
CREATE TABLE NOTIFICACIONES (
    id_notificacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('CONFIRMACION_CITA', 'RECORDATORIO_24H', 'ALERTA_VACUNA', 'RECIBO_PAGO')),
    canal VARCHAR(20) NOT NULL CHECK (canal IN ('EMAIL', 'PUSH', 'WHATSAPP', 'IN_APP')),
    mensaje TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ENVIADA', 'FALLIDA')),
    fecha_programada TIMESTAMP NULL,
    fecha_envio TIMESTAMP NULL,
    CONSTRAINT fk_notificacion_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIOS(id_usuario) ON DELETE CASCADE
);

